package com.ohmz.tday.shared.layout.export

import com.ohmz.tday.shared.layout.LayoutTokens
import java.io.File
import kotlin.system.exitProcess

/**
 * Carries [LayoutTokens] to the two clients that cannot read Kotlin.
 *
 * The same shape as `exportMotionTokens` and `exportListIconTable`: one `export` task
 * that writes committed artifacts and one `verify` task (`--check`) that fails CI when
 * they are stale. Android needs no artifact; it imports `LayoutTokens` from `:shared`
 * the way it already imports `ListIconInference`.
 *
 * Raw values only. The rule that turns them into a gap lives in each client, next to
 * the code that knows its own safe area and header height.
 */
object LayoutTokenExporter {

    private const val IOS_ARTIFACT = "ios-swiftUI/Tday/UI/Theme/TdayLayoutGenerated.swift"
    private const val WEB_ARTIFACT = "tday-web/src/generated/layout-tokens.ts"

    private const val BANNER_SOURCE =
        "Source of truth: shared/src/commonMain/kotlin/com/ohmz/tday/shared/layout/LayoutTokens.kt"
    private const val BANNER_REGEN = "Regenerate with: ./gradlew :shared:exportLayoutTokens"

    fun run(rootDir: File, check: Boolean): Boolean {
        val outputs = linkedMapOf(IOS_ARTIFACT to buildIos(), WEB_ARTIFACT to buildWeb())
        return if (check) verify(rootDir, outputs) else write(rootDir, outputs)
    }

    /** `36.0` as `36`, `0.38` as `0.38` — one spelling that is valid in Swift and TypeScript. */
    private fun num(value: Double): String =
        if (value % 1.0 == 0.0) value.toLong().toString() else value.toString()

    private fun buildIos(): String = buildString {
        appendLine("// GENERATED by :shared:exportLayoutTokens — do not edit by hand.")
        appendLine("// $BANNER_SOURCE")
        appendLine("// $BANNER_REGEN")
        appendLine("//")
        appendLine("// Raw values only. The rule that spends them lives beside the screens that")
        appendLine("// know their own safe area, in `TdayLayout.swift`.")
        appendLine()
        appendLine("import CoreGraphics")
        appendLine()
        appendLine("enum TdayLayoutGenerated {")
        appendLine()
        appendLine("    /// Where content under a hero title starts, as a fraction of the screen height.")
        appendLine("    static let contentStartRatio: CGFloat = ${num(LayoutTokens.ContentStartRatio)}")
        appendLine("    /// The least the gap under the title may be (the fade band plus 6).")
        appendLine("    static let contentGapMin: CGFloat = ${num(LayoutTokens.ContentGapMin)}")
        appendLine("    /// The most the gap under the title may be.")
        appendLine("    static let contentGapMax: CGFloat = ${num(LayoutTokens.ContentGapMax)}")
        appendLine("    /// The empty-scene slot's height, as a fraction of the screen height.")
        appendLine("    static let emptySlotRatio: CGFloat = ${num(LayoutTokens.EmptySlotRatio)}")
        appendLine("}")
    }

    private fun buildWeb(): String = buildString {
        appendLine("// GENERATED by :shared:exportLayoutTokens — do not edit by hand.")
        appendLine("// $BANNER_SOURCE")
        appendLine("// $BANNER_REGEN")
        appendLine("//")
        appendLine("// Raw values only. The rule that spends them is `src/lib/layoutTokens.ts`.")
        appendLine()
        appendLine("export const LAYOUT_TOKENS = {")
        appendLine("  /** Where content under a hero title starts, as a fraction of the screen height. */")
        appendLine("  contentStartRatio: ${num(LayoutTokens.ContentStartRatio)},")
        appendLine("  /** The least the gap under the title may be, in px (the fade band plus 6). */")
        appendLine("  contentGapMin: ${num(LayoutTokens.ContentGapMin)},")
        appendLine("  /** The most the gap under the title may be, in px. */")
        appendLine("  contentGapMax: ${num(LayoutTokens.ContentGapMax)},")
        appendLine("  /** The empty-scene slot's height, as a fraction of the screen height. */")
        appendLine("  emptySlotRatio: ${num(LayoutTokens.EmptySlotRatio)},")
        appendLine("} as const;")
    }

    private fun write(rootDir: File, outputs: Map<String, String>): Boolean {
        outputs.forEach { (rel, content) ->
            val file = File(rootDir, rel)
            file.parentFile.mkdirs()
            file.writeText(content)
            println("  wrote $rel")
        }
        println("Layout tokens exported (${outputs.size} files).")
        return true
    }

    private fun verify(rootDir: File, outputs: Map<String, String>): Boolean {
        val stale = outputs.filter { (rel, content) ->
            val file = File(rootDir, rel)
            !file.exists() || file.readText() != content
        }.keys
        if (stale.isEmpty()) {
            println("Layout tokens are up to date (${outputs.size} files).")
            return true
        }
        System.err.println("Layout tokens are STALE. Run ./gradlew :shared:exportLayoutTokens and commit:")
        stale.forEach { System.err.println("  - $it") }
        return false
    }
}

fun main(args: Array<String>) {
    val rootDir = File(args.firstOrNull { !it.startsWith("--") } ?: ".").absoluteFile
    val check = args.contains("--check")
    val ok = LayoutTokenExporter.run(rootDir, check)
    if (!ok) exitProcess(1)
}

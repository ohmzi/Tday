#!/usr/bin/env python3
"""Generate the Android widget watermark drawables from the shared Lucide glyphs.

Every widget watermark is drawn the way the Today widget's moon is: a FILLED vector with its 10%
weight baked in as fillAlpha, shown at full ImageView alpha, recoloured by a SRC_ATOP colour filter
that keeps the baked alpha. Lucide glyphs are stroked outlines, and some launchers draw nothing
for a stroked glyph faded with setImageAlpha (or with a baked strokeAlpha), so the strokes are
converted to filled outlines here.

Outputs (all under android-compose/app/src/main/res/drawable/):
  widget_watermark_<glyph>.xml          one per list-icon and pseudo-list glyph
  widget_empty_watermark_floater.xml    the Floater leaf, mirrored and rotated like the other marks
and android-compose/.../feature/widget/WidgetWatermarkGlyphs.kt, the glyph -> watermark map.

Run after adding a list icon:  python3 scripts/widget-watermarks.py
Needs: pip install skia-pathops fonttools
"""
import re
import sys
from pathlib import Path

import pathops
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "android-compose/app/src/main"
DRAWABLE = APP / "res/drawable"
LIST_ICONS = APP / "java/com/ohmz/tday/compose/ui/theme/TdayListIcons.kt"
LIST_WIDGET = APP / "java/com/ohmz/tday/compose/feature/widget/ListTasksWidget.kt"
MAP_OUT = APP / "java/com/ohmz/tday/compose/feature/widget/WidgetWatermarkGlyphs.kt"
WATERMARK_ALPHA = "0.10"


def glyph_names() -> list[str]:
    names = set(re.findall(r"R\.drawable\.ic_lucide_([a-z0-9_]+)", LIST_ICONS.read_text()))
    names |= set(re.findall(r"R\.drawable\.ic_lucide_([a-z0-9_]+)", LIST_WIDGET.read_text()))
    return sorted(names)


def outline(glyph: str, mirror: bool = False) -> str:
    xml = (DRAWABLE / f"ic_lucide_{glyph}.xml").read_text()
    paths = re.findall(r"<path(.*?)/>", xml, re.S)
    result = pathops.Path()
    for attrs in paths:
        data = re.search(r'android:pathData="([^"]+)"', attrs).group(1)
        width = float(re.search(r'android:strokeWidth="([^"]+)"', attrs).group(1))
        source = pathops.Path()
        parse_path(data, source.getPen())
        source.stroke(width, pathops.LineCap.ROUND_CAP, pathops.LineJoin.ROUND_JOIN, 4)
        source.convertConicsToQuads()
        result = pathops.op(result, source, pathops.PathOp.UNION, fix_winding=True)
    if mirror:
        result = result.transform(-1, 0, 0, 1, 24, 0)
    result.convertConicsToQuads()
    result.simplify(fix_winding=True)
    return to_svg(result)


def to_svg(path: pathops.Path) -> str:
    # SVGPathPen decomposes pathops' implied-on-curve quadratic runs into plain Q segments.
    pen = SVGPathPen(None, ntos=lambda v: ("%.3f" % v).rstrip("0").rstrip(".") or "0")
    path.draw(pen)
    return pen.getCommands()


HEADER = "<?xml version=\"1.0\" encoding=\"utf-8\"?>"


def vector(comment: str, data: str, color: str, rotation: str | None) -> str:
    path = (
        f'<path\n            android:fillAlpha="{WATERMARK_ALPHA}"\n'
        f'            android:fillColor="{color}"\n'
        f'            android:pathData="{data}" />'
    )
    body = (
        f'    <group\n        android:pivotX="12"\n        android:pivotY="12"\n        android:rotation="{rotation}">\n        {path}\n    </group>'
        if rotation
        else "    " + path.replace("\n            ", "\n        ")
    )
    return (
        f"{HEADER}<!-- {comment}\n     Generated by scripts/widget-watermarks.py; do not edit by hand. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="180dp"\n    android:height="180dp"\n'
        '    android:viewportWidth="24"\n    android:viewportHeight="24">\n'
        f"{body}\n</vector>\n"
    )


def main() -> int:
    names = glyph_names()
    for name in names:
        (DRAWABLE / f"widget_watermark_{name}.xml").write_text(
            vector(
                f"Widget watermark for the lucide {name.replace('_', '-')} list glyph (ISC, https://lucide.dev):\n"
                "     the stroked glyph as a filled outline at 10% weight, recoloured by the widget.",
                outline(name),
                "#FFFFFFFF",
                None,
            )
        )
    (DRAWABLE / "widget_empty_watermark_floater.xml").write_text(
        vector(
            "Floater widget watermark: the lucide leaf (ISC, https://lucide.dev) as a filled outline at\n"
            "     10% weight, mirrored to point the way the iOS \"leaf\" symbol does, rotated -7 like the\n"
            "     other widget watermarks.",
            outline("leaf", mirror=True),
            "@color/tday_widget_floater_accent",
            "-7",
        )
    )
    entries = "\n".join(f"    R.drawable.ic_lucide_{n} to R.drawable.widget_watermark_{n}," for n in names)
    MAP_OUT.write_text(
        "// Generated by scripts/widget-watermarks.py; do not edit by hand.\n"
        "package com.ohmz.tday.compose.feature.widget\n\n"
        "import com.ohmz.tday.compose.R\n\n"
        "/** Each list glyph's filled, pre-weighted widget watermark (see scripts/widget-watermarks.py). */\n"
        "internal val WidgetWatermarkForGlyph: Map<Int, Int> = mapOf(\n"
        f"{entries}\n)\n"
    )
    print(f"{len(names)} glyph watermarks + floater leaf")
    return 0


if __name__ == "__main__":
    sys.exit(main())
